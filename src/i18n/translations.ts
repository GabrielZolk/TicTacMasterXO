// Every valid dotted path into the pt translations tree, derived automatically.
// Hand-maintaining this list meant new sections (gravity, blind, gameResult,
// actions, bomb, mirror…) were missing and every t() call on them was a type
// error, so the type is now generated from the translations object itself.
type DotPaths<T> = {
  [K in keyof T & string]: T[K] extends string
    ? K
    : T[K] extends Record<string, unknown>
      ? `${K}.${DotPaths<T[K]>}`
      : never;
}[keyof T & string];

export type NestedTranslationKey = DotPaths<(typeof translations)['pt']>;
